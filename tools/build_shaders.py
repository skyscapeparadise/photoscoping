#!/usr/bin/env python3
"""Compiles src/gpu/shaders/*.{vert,frag} into an embeddable C++ header.

GLSL is the source of truth. It compiles to SPIR-V with glslc, then to MSL with
spirv-cross. Only MSL is emitted today because Metal is the only backend wired
up, but SPIR-V is what Vulkan wants and DXIL is one spirv-cross flag away -- so
authoring in GLSL is what keeps Windows and Linux a build-step change rather
than a shader rewrite.

glslc (shaderc) and spirv-cross are *build* tools, not shipped libraries, so
they are required rather than vendored -- the output is deterministic and
nothing links against them.

SDL_GPU's resource-set convention (SDL_gpu.h) is what makes the generated MSL
land on the right indices without any post-processing:
  vertex   -> set 0 sampled textures, set 1 uniform buffers
  fragment -> set 2 sampled textures, set 3 uniform buffers
--msl-decoration-binding is load-bearing. Without it spirv-cross numbers Metal
resources in order of *first use* inside the shader body and ignores the GLSL
`binding` decoration. Any shader that samples its textures in a different order
than it declares them then binds them backwards, with no diagnostic anywhere --
it just renders the wrong texture. With the flag the binding number is the Metal
index, so declaration order is the only thing that matters. check_bindings()
below asserts this rather than trusting it.

Verified: spirv-cross emits buffer(0) for the uniform and texture(0..3) for the
samplers, which is exactly what SDL_CreateGPUShader expects.
"""

import pathlib
import shutil
import re
import subprocess
import sys

# (source file, stage, generated C++ identifier, MSL entry point)
SHADERS = [
    ("quad.vert",    "vert", "kQuadVertex",     "vs_main"),
    ("ingest.frag",  "frag", "kIngestFragment",  "fs_main"),
    ("display.frag", "frag", "kDisplayFragment", "fs_main"),
    ("nebula.frag",  "frag", "kNebulaFragment",  "fs_main"),
    ("ui.vert",         "vert", "kUiVertex",          "vs_main"),
    ("ui.frag",         "frag", "kUiFragment",        "fs_main"),
    ("encode.vert",     "vert", "kEncodeVertex",      "vs_main"),
    ("encode_sdr.frag", "frag", "kEncodeFragmentSdr", "fs_main"),
    ("encode_edr.frag", "frag", "kEncodeFragmentEdr", "fs_main"),
]


def require(tool: str, hint: str) -> str:
    path = shutil.which(tool)
    if not path:
        sys.exit(
            f"error: '{tool}' not found on PATH.\n"
            f"  It is a build-time shader tool, not a shipped dependency.\n"
            f"  Install it with: {hint}"
        )
    return path


def check_bindings(name: str, glsl: str, msl: str) -> None:
    """Assert each sampler landed at the Metal index its GLSL binding asked for.

    This exists because getting it wrong is invisible: the shader compiles, the
    pipeline builds, nothing logs, and the only symptom is that two textures are
    swapped in the output image.
    """
    declared = {
        int(m.group(1)): m.group(2)
        for m in re.finditer(
            r"binding\s*=\s*(\d+)\s*\)\s*uniform\s+sampler[23]D\s+(\w+)", glsl)
    }
    if not declared:
        return
    actual = {int(m.group(2)): m.group(1)
              for m in re.finditer(r"texture[23]d<[^>]*>\s+(\w+)\s*\[\[texture\((\d+)\)\]\]", msl)}
    for slot, want in sorted(declared.items()):
        got = actual.get(slot)
        if got != want:
            raise SystemExit(
                f"{name}: sampler binding {slot} is '{want}' in GLSL but "
                f"'{got}' at [[texture({slot})]] in the generated MSL. "
                f"spirv-cross reordered the resources -- check that "
                f"--msl-decoration-binding is still being passed.")


def main() -> int:
    root = pathlib.Path(__file__).resolve().parent.parent
    src_dir = root / "src" / "gpu" / "shaders"
    # The output path is required rather than defaulted into src/. A generated
    # header sitting in the source tree shadows the one the build makes -- src
    # comes first on the include path -- so an edited shader would compile
    # against a stale copy, silently, which is exactly what happened.
    if len(sys.argv) < 2:
        print("usage: build_shaders.py <output header>", file=sys.stderr)
        return 1
    out_path = pathlib.Path(sys.argv[1])
    tmp = out_path.parent / ".shader_build"
    tmp.mkdir(parents=True, exist_ok=True)

    glslc = require("glslc", "brew install shaderc")
    cross = require("spirv-cross", "brew install spirv-cross")

    parts = ['''#pragma once

// GENERATED by tools/build_shaders.py from src/gpu/shaders/*.{vert,frag}
// Do not edit. Edit the GLSL and rebuild.

namespace ps::gpu::shaders {
''']

    for name, stage, ident, entry in SHADERS:
        source = src_dir / name
        spv = tmp / (name + ".spv")
        subprocess.run(
            [glslc, f"-fshader-stage={stage}", "-I", str(src_dir),
             str(source), "-o", str(spv)],
            check=True,
        )
        # spirv-cross always names the entry point "main"; rename it to the
        # vs_main/fs_main convention SDL_CreateGPUShader is told to look for.
        msl = subprocess.run(
            [cross, str(spv), "--msl", "--msl-decoration-binding",
             "--rename-entry-point", "main", entry, stage],
            check=True, capture_output=True, text=True,
        ).stdout
        check_bindings(name, source.read_text(), msl)
        parts.append(f'\n// ---- {name} ----\ninline constexpr const char* {ident} = R"MSL(\n{msl})MSL";\n')

    parts.append("\n}  // namespace ps::gpu::shaders\n")
    out_path.write_text("".join(parts))
    print(f"generated {out_path} from {len(SHADERS)} shaders")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
